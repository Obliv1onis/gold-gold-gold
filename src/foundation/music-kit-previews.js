/** Resolve a preview for normal and StatTrak music-kit market names. */
export function getMusicKitPreviewId(name) {
  if (typeof name !== 'string') return '';
  const suffix = name
    .replace(/^StatTrak™\s+/, '')
    .replace(/^Music Kit\s*\|\s*/, '')
    .trim();
  return MUSIC_KIT_PREVIEWS.get(suffix) ?? '';
}
