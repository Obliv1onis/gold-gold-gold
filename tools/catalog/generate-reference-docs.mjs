#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const ROOT = resolve('.');
const OUT = resolve(ROOT, 'design/reference');
const checkOnly = process.argv.slice(2).includes('--check');
const unknownArgs = process.argv.slice(2).filter(arg => arg !== '--check');
if (unknownArgs.length) throw new Error(`Unknown argument: ${unknownArgs[0]}`);
const DATA_LINKS = {
  cases: '../../public/data/cases.json',
  capsules: '../../public/data/capsules.json',
  souvenirs: '../../public/data/souvenirs.json',
  others: '../../public/data/others.json',
  market: '../../public/data/market-items.json',
};

const CASE_RARITIES = [
  'rare_special', 'covert', 'classified', 'restricted', 'mil_spec',
  'industrial_grade', 'consumer_grade',
];
const CAPSULE_RARITIES = ['extraordinary', 'exotic', 'remarkable', 'high_grade'];
const LABELS = {
  rare_special: 'Rare Special',
  covert: 'Covert',
  classified: 'Classified',
  restricted: 'Restricted',
  mil_spec: 'Mil-Spec',
  industrial_grade: 'Industrial Grade',
  consumer_grade: 'Consumer Grade',
  extraordinary: 'Extraordinary',
  exotic: 'Exotic',
  remarkable: 'Remarkable',
  high_grade: 'High Grade',
  charm_capsule: 'Charm Collections',
  patch_pack: 'Patch Collections',
  pin_capsule: 'Collectible Pin Capsules',
  music_kit_box: 'Music Kit Boxes',
};

const [caseData, capsuleData, souvenirData, otherData, marketData] = await Promise.all([
  readJson('public/data/cases.json'),
  readJson('public/data/capsules.json'),
  readJson('public/data/souvenirs.json'),
  readJson('public/data/others.json'),
  readJson('public/data/market-items.json'),
]);

const cases = caseData.cases;
const capsules = capsuleData.capsules;
const souvenirs = souvenirData.cases;
const others = otherData.capsules;
const marketItems = marketData.items;

function readJson(path) {
  return readFile(resolve(ROOT, path), 'utf8').then(JSON.parse);
}

function escapeTable(value) {
  return String(value ?? '—').replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function money(value) {
  return Number.isFinite(value) ? `$${value.toFixed(2)}` : '—';
}

function date(value) {
  return value || '—';
}

function sortByNewest(entries) {
  return [...entries].sort((a, b) => {
    if (!a.release_date && !b.release_date) return a.name.localeCompare(b.name);
    if (!a.release_date) return 1;
    if (!b.release_date) return -1;
    return b.release_date.localeCompare(a.release_date) || a.name.localeCompare(b.name);
  });
}

function itemCount(entry, poolKey) {
  return Object.values(entry[poolKey] ?? {}).flat().length;
}

function caseItemName(item) {
  if (item.skin?.startsWith('★')) {
    const finish = item.skin.slice(1).trim();
    return finish.toLowerCase() === 'vanilla'
      ? `★ ${item.weapon}`
      : `★ ${item.weapon} | ${finish}`;
  }
  return `${item.weapon} | ${item.skin}`;
}

function generatedHeader(title, dataKey, catalog, description) {
  return [
    `# ${title}`,
    '',
    `> Generated from [${dataKey}.json](${DATA_LINKS[dataKey]}). Do not edit this file manually.`,
    `> Catalogue verified: ${catalog?.verified_on ?? 'unknown'}.`,
    '',
    description,
    '',
  ];
}

function renderWeights(weights, order) {
  const parts = order
    .filter(rarity => (weights?.[rarity] ?? 0) > 0)
    .map(rarity => `${LABELS[rarity]} ${weights[rarity]}%`);
  return parts.join(' · ');
}

function renderCaseContents(entries, title, dataKey, catalog) {
  const lines = generatedHeader(
    title,
    dataKey,
    catalog,
    `Complete simulator contents for ${entries.length} containers.`,
  );
  lines.push('## Rarity key', '');
  for (const rarity of CASE_RARITIES) lines.push(`- **${LABELS[rarity]}**`);
  lines.push('', '## Containers', '');

  for (const entry of sortByNewest(entries)) {
    lines.push(`### ${entry.name}`, '');
    lines.push(`- Release date: ${date(entry.release_date)}`);
    lines.push(`- ${catalog?.price_source ? 'Steam market price' : 'Fallback price'}: ${money(entry.market_price)}`);
    lines.push(`- Items: ${itemCount(entry, 'items')}`);
    lines.push(`- Drop weights: ${renderWeights(entry.rarity_weights, CASE_RARITIES)}`, '');
    for (const rarity of CASE_RARITIES) {
      const items = entry.items?.[rarity] ?? [];
      if (!items.length) continue;
      lines.push(`#### ${LABELS[rarity]} (${items.length})`, '');
      for (const item of items) lines.push(`- ${caseItemName(item)}`);
      lines.push('');
    }
  }
  return lines;
}

function renderCapsuleContents(entries) {
  const lines = generatedHeader(
    'Sticker Capsule and Autograph Contents',
    'capsules',
    capsuleData.catalog,
    `Complete simulator contents for ${entries.length} sticker and autograph capsules.`,
  );
  lines.push('## Containers', '');
  for (const entry of sortByNewest(entries)) {
    lines.push(`### ${entry.name}`, '');
    lines.push(`- Release date: ${date(entry.release_date)}`);
    lines.push(`- Fallback price: ${money(entry.price)}`);
    lines.push(`- Items: ${itemCount(entry, 'tiers')}`);
    lines.push(`- Drop weights: ${renderWeights(entry.rarity_weights, CAPSULE_RARITIES)}`, '');
    for (const rarity of CAPSULE_RARITIES) {
      const items = entry.tiers?.[rarity] ?? [];
      if (!items.length) continue;
      lines.push(`#### ${LABELS[rarity]} (${items.length})`, '');
      for (const item of items) lines.push(`- ${item.name}`);
      lines.push('');
    }
  }
  return lines;
}

function renderOtherContents(entries) {
  const lines = generatedHeader(
    'Other Cosmetic Container Contents',
    'others',
    otherData.catalog,
    `Complete simulator contents for ${entries.length} charm, patch, pin, and music-kit containers.`,
  );
  for (const type of ['charm_capsule', 'patch_pack', 'pin_capsule', 'music_kit_box']) {
    const group = sortByNewest(entries.filter(entry => entry.type === type));
    lines.push(`## ${LABELS[type]} (${group.length})`, '');
    for (const entry of group) {
      lines.push(`### ${entry.name}`, '');
      lines.push(`- Release date: ${date(entry.release_date)}`);
      lines.push(`- Fallback price: ${money(entry.price)}`);
      lines.push(`- Items: ${itemCount(entry, 'tiers')}`);
      lines.push(`- Drop weights: ${renderWeights(entry.rarity_weights, CAPSULE_RARITIES)}`, '');
      for (const rarity of CAPSULE_RARITIES) {
        const items = entry.tiers?.[rarity] ?? [];
        if (!items.length) continue;
        lines.push(`#### ${LABELS[rarity]} (${items.length})`, '');
        for (const item of items) lines.push(`- ${item.name}`);
        lines.push('');
      }
    }
  }
  return lines;
}

function renderPriceIndex(title, dataKey, catalog, entries, typeLabel, priceKey, poolKey) {
  const steamPriced = catalog?.price_source === 'Steam Community Market';
  const lines = generatedHeader(
    title,
    dataKey,
    catalog,
    steamPriced
      ? `Prices below are Steam Community Market snapshots verified ${catalog.price_verified_at ?? 'at the latest catalogue update'}; visible items refresh at runtime.`
      : 'Prices below are simulator fallback values, not live Steam Community Market quotes.',
  );
  lines.push(`| Container | Type | Release date | Items | ${steamPriced ? 'Steam price' : 'Fallback price'} |`);
  lines.push('| --- | --- | --- | ---: | ---: |');
  for (const entry of sortByNewest(entries)) {
    lines.push(
      `| ${escapeTable(entry.name)} | ${escapeTable(typeLabel(entry))} | ${date(entry.release_date)} | `
      + `${itemCount(entry, poolKey)} | ${money(entry[priceKey])} |`,
    );
  }
  lines.push('');
  return lines;
}

function renderRareSpecials(entries) {
  const withSpecials = entries.filter(entry => entry.items?.rare_special?.length);
  const lines = generatedHeader(
    'Rare Special Item Pools',
    'cases',
    caseData.catalog,
    `Rare-special pools for ${withSpecials.length} cases and terminals.`,
  );
  lines.push('## Containers', '');
  for (const entry of sortByNewest(withSpecials)) {
    lines.push(`### ${entry.name} (${entry.items.rare_special.length})`, '');
    lines.push(`- Drop weight: ${entry.rarity_weights.rare_special}%`, '');
    for (const item of entry.items.rare_special) lines.push(`- ${caseItemName(item)}`);
    lines.push('');
  }
  return lines;
}

function renderMusicKits(entries, standaloneItems) {
  const boxes = entries.filter(entry => entry.type === 'music_kit_box');
  const directItems = standaloneItems.filter(entry => entry.capsuleType === 'music_kit_box');
  const kits = new Map();
  for (const box of boxes) {
    for (const [rarity, items] of Object.entries(box.tiers ?? {})) {
      for (const item of items) {
        const statTrak = item.name.startsWith('StatTrak™ ');
        const name = item.name
          .replace(/^StatTrak™\s+/, '')
          .replace('TWERL and Ekko & Sidetrack, Under Bright Lights', 'TWERL, Ekko & Sidetrack, Under Bright Lights');
        const current = kits.get(name) ?? { name, variants: new Set(), rarities: new Set(), boxes: new Set() };
        current.variants.add(statTrak ? 'StatTrak™' : 'Normal');
        current.rarities.add(LABELS[rarity] ?? rarity);
        current.boxes.add(box.name);
        kits.set(name, current);
      }
    }
  }
  for (const item of directItems) {
    const statTrak = item.name.startsWith('StatTrak™ ');
    const name = item.name.replace(/^StatTrak™\s+/, '');
    const current = kits.get(name) ?? { name, variants: new Set(), rarities: new Set(), boxes: new Set() };
    current.variants.add(statTrak ? 'StatTrak™' : 'Normal');
    current.rarities.add(LABELS[item.rarity] ?? item.rarity);
    current.boxes.add('Direct Steam market');
    kits.set(name, current);
  }
  const paired = [...kits.values()].filter(kit => kit.variants.size === 2).length;
  const statTrakOnly = [...kits.values()].filter(kit => kit.variants.size === 1 && kit.variants.has('StatTrak™')).length;
  const directCount = new Set(directItems.map(item => item.name.replace(/^StatTrak™\s+/, ''))).size;
  const lines = [
    '# Music Kits',
    '',
    `> Generated from [others.json](${DATA_LINKS.others}) and [market-items.json](${DATA_LINKS.market}). Do not edit this file manually.`,
    `> Catalogue verified: ${marketData.catalog?.price_verified_at ?? otherData.catalog?.verified_on ?? 'unknown'}.`,
    '',
    `${kits.size} unique music kits are available in the simulator: ${kits.size - directCount} through `
      + `${boxes.length} music-kit boxes and ${directCount} directly through the Steam market. `
      + `${paired} have Normal and StatTrak™ variants; ${statTrakOnly} are StatTrak™-only.`,
    '',
  ];
  lines.push('| Music kit | Variants | Rarity | Available from |');
  lines.push('| --- | --- | --- | --- |');
  for (const kit of [...kits.values()].sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(
      `| ${escapeTable(kit.name)} | ${escapeTable([...kit.variants].join(' + '))} | `
      + `${escapeTable([...kit.rarities].join(', '))} | `
      + `${escapeTable([...kit.boxes].join(', '))} |`,
    );
  }
  lines.push('');
  return lines;
}

const docs = new Map([
  ['cases.md', renderCaseContents(cases.filter(entry => entry.type === 'weapon_case'), 'Weapon Case Contents', 'cases', caseData.catalog)],
  ['terminals.md', renderCaseContents(cases.filter(entry => entry.type === 'terminal'), 'Terminal Contents', 'cases', caseData.catalog)],
  ['capsules.md', renderCapsuleContents(capsules)],
  ['souvenirs.md', renderCaseContents(souvenirs, 'Souvenir Package Contents', 'souvenirs', souvenirData.catalog)],
  ['others.md', renderOtherContents(others)],
  ['rare-specials.md', renderRareSpecials(cases)],
  ['music-kits.md', renderMusicKits(others, marketItems)],
  ['case-price.md', renderPriceIndex('Weapon Case Price Reference', 'cases', caseData.catalog, cases, entry => entry.type === 'terminal' ? 'Terminal' : 'Weapon Case', 'market_price', 'items')],
  ['capsule-price.md', renderPriceIndex('Sticker Capsule Price Reference', 'capsules', capsuleData.catalog, capsules, () => 'Sticker / Autograph Capsule', 'price', 'tiers')],
  ['souvenir-price.md', renderPriceIndex('Souvenir Package Price Reference', 'souvenirs', souvenirData.catalog, souvenirs, () => 'Souvenir Package', 'market_price', 'items')],
  ['other-price.md', renderPriceIndex('Other Container Price Reference', 'others', otherData.catalog, others, entry => LABELS[entry.type] ?? entry.type, 'price', 'tiers')],
]);

if (checkOnly) {
  const stale = [];
  await Promise.all([...docs].map(async ([name, lines]) => {
    const expected = `${lines.join('\n').trim()}\n`;
    const current = await readFile(resolve(OUT, name), 'utf8').catch(() => '');
    if (current !== expected) stale.push(name);
  }));
  if (stale.length) {
    console.error(`Reference documents are stale: ${stale.sort().join(', ')}`);
    process.exitCode = 1;
  } else {
    console.log(`Reference check passed: ${docs.size} documents are current.`);
  }
} else {
  await Promise.all(
    [...docs].map(([name, lines]) => writeFile(resolve(OUT, name), `${lines.join('\n').trim()}\n`)),
  );
  console.log(`Generated ${docs.size} reference documents in design/reference/.`);
}
